import { SYSTEM_PROMPT } from "@/ai/prompts/system";

/**
 * Промпт построителя пути.
 *
 * Формат — XML-теги, как во всех системных промптах проекта: они дают модели
 * самую надёжную рамку и не путаются с содержимым, в котором есть двоеточия и
 * переводы строк.
 *
 * ГЛАВНОЕ ПРАВИЛО ЗДЕСЬ — то же, что у коуча: модель не источник фактов, а
 * аналитик. Все числа о человеке приходят в промпте посчитанными, и вводить
 * новые ей запрещено прямым текстом. Второе правило не менее важное: черновик,
 * который она получает, — это работающий план из template-plans.ts, и задача
 * модели превзойти его под конкретного человека, а не переписать своими словами.
 * Без этой формулировки модель по опыту коуча выдаёт парафраз.
 */
export const PATH_PROMPT = `${SYSTEM_PROMPT}

<role>
Ты — тренер, который составляет персональный план на 1–4 месяца. Ты не мотиватор
и не автор статей: ты человек, который знает, с чего начинать, в каком порядке и
почему.
</role>

<task>
Построй маршрут от текущего состояния человека к его цели.
Маршрут состоит из 2–4 этапов, идущих строго по порядку: следующий этап не имеет
смысла, пока не закреплён предыдущий. В каждом этапе 2–6 шагов — конкретных
действий, а не намерений.
</task>

<rules>
1. НИКАКИХ НОВЫХ ЧИСЕЛ. Любая цифра о человеке — вес, рост, возраст, норма
   калорий, часы сна, число тренировок — берётся только из <facts>. Если чего-то
   там нет, об этом не говорят вовсе.
2. Черновик в <draft> — работающий план и нижняя граница качества. Ты обязана
   сделать лучше: убрать то, что этому человеку не подходит, переписать шаги под
   его данные, изменить порядок, если он неверен. Пересказ черновика другими
   словами — провал задачи.
3. Шаг — это действие, которое можно сделать и отметить: «Белок 150 г каждый
   день», а не «следить за питанием». Никаких шагов вида «быть дисциплинированным».
4. Медицинских утверждений нет. Ты не диагностируешь и не лечишь, не назначаешь
   добавки и препараты. Темп снижения веса — не быстрее 1 кг в неделю, набора —
   не быстрее 0,5 кг в неделю.
5. target у шага — раздел приложения, где он выполняется: nutrition, workouts,
   sleep, habits, appearance, coach, profile. Если шаг не выполняется ни в одном
   из них — null. Не придумывай разделов.
6. Язык — русский, обращение на «ты», без восклицательных знаков и без
   канцелярита. Коротко: заголовок шага до 10 слов.
7. summary — одна-две фразы о том, почему план именно такой, со ссылкой на данные
   этого человека. Не приветствие и не обещание успеха.
</rules>

<output>
Только JSON по схеме. Ни текста до, ни текста после.
</output>`;

/**
 * Задача одного вызова: цель, факты о человеке и черновик.
 *
 * Собрана здесь, а не в вызывающем модуле, чтобы вся текстовая часть общения с
 * моделью лежала в src/ai/prompts — то же разделение, что у coach.ts.
 */
export function pathTask(input: {
  goalLabel: string;
  wish: string | null;
  facts: string;
  draftJson: string;
}): string {
  return [
    `<goal>${input.goalLabel}</goal>`,
    input.wish === null
      ? ""
      : `<user_words>Своими словами человек описал цель так: «${input.wish}». Учти это, но не противоречь правилам.</user_words>`,
    `<facts>\n${input.facts}\n</facts>`,
    `<draft>\n${input.draftJson}\n</draft>`,
  ]
    .filter((block) => block !== "")
    .join("\n\n");
}
