/**
 * Основной бот — тот, внутри которого живёт само приложение.
 *
 * Второй публичный адрес продукта после бота поддержки, и путать их нельзя:
 * это две разные двери. Раньше их было не две, а одна — каждая кнопка
 * «Начать бесплатно» на лендинге вела в поддержку, то есть человек, решивший
 * попробовать Nova, попадал в чат «опишите вашу проблему». Пользователь,
 * который хотел продукт, получал форму обращения; поддержка получала поток
 * людей, которым нечего сказать. Худший из возможных первых экранов.
 *
 * Разделение простое и должно таким остаться:
 *
 *   этот файл  — «хочу пользоваться»  → Mini App;
 *   support.ts — «хочу что-то спросить, сломалось, хочу оплатить» → тикет.
 *
 * Как и support.ts, модуль намеренно без `server-only` и без доступа к env:
 * его импортируют клиентские компоненты лендинга. Username бота — публичная
 * информация, он напечатан на кнопке; секрет — токен, и он живёт в env.
 */

/** Username основного бота, без @. Проверено через getMe. */
export const TELEGRAM_APP_BOT_USERNAME = "NovaEvaluation_bot";

/**
 * Куда ведёт «Начать бесплатно».
 *
 * `?startapp` открывает Mini App сразу, если в @BotFather у бота настроено
 * Main Mini App. Если не настроено — Telegram просто откроет чат с ботом, где
 * приложение запускается кнопкой меню. Деградация тихая и безвредная: в обоих
 * случаях человек оказывается у основного бота, а не в поддержке.
 */
export const TELEGRAM_APP_URL = `https://t.me/${TELEGRAM_APP_BOT_USERNAME}?startapp`;

/** Тот же бот в тексте. */
export const TELEGRAM_APP_HANDLE = `@${TELEGRAM_APP_BOT_USERNAME}`;
