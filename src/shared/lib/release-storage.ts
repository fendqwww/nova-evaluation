/**
 * Какую версию Nova человек уже видел.
 *
 * ЗАЧЕМ. Приложение обновляется молча: экраны меняются, разделы переезжают, и
 * человек, открывший Nova после обновления, обнаруживает, что кнопка не там,
 * где была вчера. Разбирается он в этом сам, и половина изменений остаётся
 * незамеченной вовсе — вместе с работой, которая в них вложена. Одна короткая
 * записка при первом запуске новой версии закрывает и то и другое.
 *
 * ПОЧЕМУ НА УСТРОЙСТВЕ, А НЕ В БАЗЕ. Это не факт о пользователе, а факт об
 * установке: «этот экран уже показывали здесь». Столбец в User означал бы
 * миграцию и запрос ради булева значения, которое ничего не решает — худшее,
 * что может случиться при потере хранилища, это записка, показанная второй раз.
 *
 * ВСЁ ЗДЕСЬ ОБЯЗАНО ПЕРЕЖИВАТЬ ОТСУТСТВИЕ localStorage — в Telegram WebView на
 * iOS без cookies обращение к нему бросает SecurityError. То же правило, что в
 * theme-storage.ts, и по той же причине: ради записки о новинках приложение не
 * имеет права не запуститься.
 */

const RELEASE_KEY = "nova.release.seen";

/**
 * Версия, на которой человека уже поздравили с обновлением. null — не
 * показывали ничего и никогда.
 */
export function seenRelease(): string | null {
  if (typeof window === "undefined") return null;
  try {
    return window.localStorage.getItem(RELEASE_KEY);
  } catch {
    return null;
  }
}

export function markReleaseSeen(version: string): void {
  if (typeof window === "undefined") return;
  try {
    window.localStorage.setItem(RELEASE_KEY, version);
  } catch {
    // Приватный режим или отключённое хранилище: записка покажется ещё раз при
    // следующем запуске. Это деградация, а не поломка.
  }
}
