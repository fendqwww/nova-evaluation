"use client";

import { hapticFeedback } from "@tma.js/sdk-react";

/**
 * Тактильный отклик Telegram — одна точка входа на всё приложение.
 *
 * ЗАЧЕМ ОБЁРТКА, А НЕ ПРЯМЫЕ ВЫЗОВЫ. Методы SDK бросают исключение, когда
 * клиент их не поддерживает (Mini Apps < 6.1), когда приложение открыто не
 * внутри Telegram и в dev-режиме, где моста нет вовсе. Прямой
 * `hapticFeedback.impactOccurred("light")` в обработчике нажатия означает, что
 * на десктопном Telegram Web кнопка перестала бы работать целиком — не из-за
 * логики, а из-за вибрации, которой там физически нет.
 *
 * Отсюда правило: вибрация — украшение, и её отсутствие не должно быть видно.
 * Каждый вызов ниже проглатывает любую ошибку и возвращает void.
 *
 * СЛОВАРЬ ЖЕСТОВ — три уровня, и они не взаимозаменяемы:
 *
 *   selection — палец перешёл с одного варианта на другой: вкладка, ячейка,
 *     шаг счётчика. Самый лёгкий отклик; его можно давать часто.
 *   tap       — совершено действие: открылся лист записи, отправлен вопрос
 *     коучу. Средний удар, соответствует нажатию, у которого есть последствие.
 *   success / warning / error — результат операции, а не факт нажатия. Даётся
 *     один раз, когда сервер ответил, и никогда — заранее.
 *
 * Разделение важно: если каждое нажатие отдаёт `success`, телефон перестаёт
 * что-либо сообщать и превращается в жужжащую игрушку.
 */

function safely(action: () => void): void {
  try {
    // Сигнал, а не поле: в @tma.js это Computed, который нужно вызвать.
    if (!hapticFeedback.isSupported()) return;
    action();
  } catch {
    // Нет моста, старый клиент, браузер вне Telegram — молча ничего.
  }
}

export const haptics = {
  /** Выбор изменился: вкладка, ячейка, шаг. */
  selection: () => safely(() => hapticFeedback.selectionChanged()),

  /** Действие совершено: открыт лист, начата тренировка, отправлен вопрос. */
  tap: () => safely(() => hapticFeedback.impactOccurred("light")),

  /** Заметное действие: старт сессии, применение шаблона. */
  press: () => safely(() => hapticFeedback.impactOccurred("medium")),

  /** Операция удалась — только по факту ответа, не по факту нажатия. */
  success: () => safely(() => hapticFeedback.notificationOccurred("success")),

  /** Операция прошла, но с оговоркой: превышена цель, запись задним числом. */
  warning: () => safely(() => hapticFeedback.notificationOccurred("warning")),

  /** Операция не удалась. */
  error: () => safely(() => hapticFeedback.notificationOccurred("error")),
};
