/**
 * Заголовок пути.
 *
 * Измеримая цель называет число: «Похудеть на 8 кг» — это то, что человек
 * сверяет с весами, а «Похудеть» проверить нельзя. Когда числа нет, остаётся
 * название цели, и это честно.
 */
function planTitle(kind: PathGoalKind, startValue: number | null, targetValue: number | null): string {
  const meta = PATH_GOAL_KIND_META[kind];
  if (!meta.measure || startValue === null || targetValue === null) return meta.label;

  const delta = Math.round(Math.abs(startValue - targetValue) * 10) / 10;
  if (delta === 0) return `${meta.label}: удержать ${startValue} кг`;

  const amount = String(delta).replace(".", ",");
  return meta.measure.direction === "down"
    ? `Похудеть на ${amount} кг`
    : `Набрать ${amount} кг`;
}

/** Одна строка о том, почему план такой. Опирается на числа, а не на настроение. */
function planSummary(kind: PathGoalKind, startValue: number | null, targetValue: number | null): string {
  const meta = PATH_GOAL_KIND_META[kind];

  if (meta.measure && startValue !== null && targetValue !== null) {
    const delta = Math.abs(startValue - targetValue);
    // 0,6 кг в неделю — середина безопасного диапазона из заголовка файла.
    const weeks = Math.max(2, Math.ceil(delta / 0.6));
    return meta.measure.direction === "down"
      ? `${Math.round(delta * 10) / 10} кг в безопасном темпе — это около ${weeks} недель. План рассчитан так, чтобы уходил жир, а не мышцы.`
      : `${Math.round(delta * 10) / 10} кг массы набираются примерно за ${weeks} недель. Быстрее — значит набрать жир вместо мышц.`;
  }

  return `${meta.tagline}. Этапы идут по порядку: следующий не имеет смысла, пока не закреплён предыдущий.`;
}

/**
 * Готовый план по цели — то, что записывается в базу, когда модель недоступна,
 * и то, что уезжает модели черновиком, когда доступна.
 */
export function templatePlan(input: {
  kind: PathGoalKind;
  startValue: number | null;
  targetValue: number | null;
}): PathPlan {
  const meta = PATH_GOAL_KIND_META[input.kind];

  return {
    title: planTitle(input.kind, input.startValue, input.targetValue),
    summary: planSummary(input.kind, input.startValue, input.targetValue),
    horizonDays: meta.horizonDays,
    stages: TEMPLATES[input.kind].map((stage) => ({
      title: stage.title,
      goal: stage.goal,
      steps: stage.steps.map((step) => ({
        title: step.title,
        hint: step.hint,
        target: step.target,
      })),
    })),
  };
}
