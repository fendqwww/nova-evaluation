import type { MuscleGroup } from "@/features/workouts/lib/exercise-visual";
import { cn } from "@/shared/lib/cn";

/**
 * Схема работающих мышц — силуэт человека с подсвеченной группой.
 *
 * ЗАЧЕМ ОНА ВООБЩЕ. Фотографий движений в приложении одиннадцать, а упражнений
 * в каталоге под шестьдесят, и так будет всегда: снимки надо лицензировать или
 * рисовать, а каталог растёт от одного запроса пользователя. Прежний запасной
 * вариант — серый прямоугольник со словом «Ноги» — честно сообщал группу мышц и
 * ровно поэтому выглядел заглушкой: подпись под ним говорила то же самое
 * дважды. Схема отвечает на тот же вопрос картинкой, то есть быстрее, чем
 * читается слово, и в списке из тридцати строк это разница между «сканирую» и
 * «читаю».
 *
 * ПОЧЕМУ SVG, А НЕ ЕЩЁ ОДИННАДЦАТЬ КАРТИНОК. Она красится токенами темы, а не
 * запечённым цветом: в светлой теме тело серое на белом, в тёмной — светлое на
 * чёрном, подсветка всегда акцентом пользователя. Растровая картинка так не
 * умеет — её пришлось бы держать в двух версиях на каждую тему и всё равно
 * перерисовывать при смене акцента. Весит она сотни байт и не делает запроса.
 *
 * ДВА РАКУРСА, А НЕ ОДИН. Спину и ягодицы спереди не показать — подсвечивать
 * там нечего, и единственный вид сзади для двух групп честнее, чем подсветка
 * «примерно этого места» на груди.
 */

type View = "front" | "back";

/** Какие части силуэта горят для каждой группы, и с какой стороны смотрим. */
const HIGHLIGHT: Record<MuscleGroup, { view: View; parts: readonly string[] }> = {
  chest: { view: "front", parts: ["chest"] },
  back: { view: "back", parts: ["lats", "traps"] },
  shoulders: { view: "front", parts: ["delts"] },
  biceps: { view: "front", parts: ["upperArms"] },
  triceps: { view: "back", parts: ["upperArms"] },
  legs: { view: "front", parts: ["thighs", "calves"] },
  glutes: { view: "back", parts: ["glutes", "thighs"] },
  core: { view: "front", parts: ["core"] },
  // Кардио — это не мышца, а режим работы: горит то, что действительно несёт
  // нагрузку в беге и на велосипеде, плюс корпус.
  cardio: { view: "front", parts: ["thighs", "calves", "core"] },
  fullBody: {
    view: "front",
    parts: ["chest", "delts", "upperArms", "core", "thighs", "calves"],
  },
};

export function MuscleMap({
  group,
  className,
}: {
  group: MuscleGroup;
  className?: string;
}) {
  const { view, parts } = HIGHLIGHT[group];
  const on = (part: string) => parts.includes(part);

  // Заливка задаётся здесь, а не классами: у подсветки цвет акцента темы, у
  // остального — приглушённый, и оба живут в CSS-переменных.
  const base = { fill: "var(--fill-strong)" } as const;
  const lit = { fill: "var(--accent)" } as const;
  const paint = (part: string) => (on(part) ? lit : base);

  return (
    <svg
      viewBox="0 0 100 160"
      aria-hidden
      className={cn("h-full w-full", className)}
    >
      {/* Голова и шея не подсвечиваются никогда — они здесь только затем,
          чтобы силуэт читался как человек, а не как набор фигур. */}
      <circle cx="50" cy="14" r="8.5" {...base} />
      <rect x="45.5" y="21" width="9" height="7" rx="3" {...base} />

      {/* Корпус: плечи шире таза, талия уже обоих. Один контур под всем
          остальным, чтобы подсвеченные части лежали на теле, а не висели. */}
      <path
        d="M32 31 Q50 25.5 68 31 L66 58 Q63.5 75 61.5 88 L38.5 88 Q36.5 75 34 58 Z"
        {...base}
      />

      {/* Дельты */}
      <ellipse cx="28.5" cy="35.5" rx="8.5" ry="7.5" {...paint("delts")} />
      <ellipse cx="71.5" cy="35.5" rx="8.5" ry="7.5" {...paint("delts")} />

      {/* Плечо руки — бицепс спереди, трицепс сзади: одна и та же часть
          силуэта, разный ракурс. */}
      <rect
        x="18.5" y="40" width="10.5" height="28" rx="5.25"
        transform="rotate(-7 23.75 54)"
        {...paint("upperArms")}
      />
      <rect
        x="71" y="40" width="10.5" height="28" rx="5.25"
        transform="rotate(7 76.25 54)"
        {...paint("upperArms")}
      />

      {/* Предплечья — вне подсветки: ни одна группа каталога на них не идёт. */}
      <rect
        x="14.5" y="66" width="9.5" height="26" rx="4.75"
        transform="rotate(-9 19.25 79)"
        {...base}
      />
      <rect
        x="76" y="66" width="9.5" height="26" rx="4.75"
        transform="rotate(9 80.75 79)"
        {...base}
      />

      {view === "front" ? (
        <>
          {/* Грудные — две половины с зазором по центральной линии. */}
          <path d="M35 32.5 Q42.5 29.5 49 31.5 L49 47.5 Q40 48.5 35.8 44 Z" {...paint("chest")} />
          <path d="M65 32.5 Q57.5 29.5 51 31.5 L51 47.5 Q60 48.5 64.2 44 Z" {...paint("chest")} />

          {/* Пресс */}
          <rect x="42" y="50" width="16" height="34" rx="5" {...paint("core")} />
        </>
      ) : (
        <>
          {/* Трапеции — от шеи к плечам, широкой трапецией.
              Зазор в 2 единицы до широчайших обязателен: без него обе фигуры
              сливались в одну и спина читалась как жилет, а не как две группы,
              которые тренируют разными движениями. */}
          <path d="M36.5 28.5 Q50 25 63.5 28.5 L58.5 43 L41.5 43 Z" {...paint("traps")} />

          {/* Широчайшие — та самая V-образная спина: широко под плечами,
              сходится к пояснице. Верхняя кромка шире трапеций, нижняя точка
              выше таза: именно это соотношение и читается как V. */}
          <path d="M33.5 45.5 L49 49 L49 80 Q40.5 73 36 60 Z" {...paint("lats")} />
          <path d="M66.5 45.5 L51 49 L51 80 Q59.5 73 64 60 Z" {...paint("lats")} />
        </>
      )}

      {/* Таз: ягодицы видно только сзади, спереди на их месте ровный контур. */}
      {view === "back" ? (
        <>
          <ellipse cx="43.5" cy="92.5" rx="9" ry="8" {...paint("glutes")} />
          <ellipse cx="56.5" cy="92.5" rx="9" ry="8" {...paint("glutes")} />
        </>
      ) : (
        <rect x="36" y="86" width="28" height="12" rx="5" {...base} />
      )}

      {/* Бёдра и голени */}
      <rect x="36.5" y="98" width="12" height="30" rx="6" {...paint("thighs")} />
      <rect x="51.5" y="98" width="12" height="30" rx="6" {...paint("thighs")} />
      <rect x="38" y="128" width="10" height="24" rx="5" {...paint("calves")} />
      <rect x="52" y="128" width="10" height="24" rx="5" {...paint("calves")} />
    </svg>
  );
}
