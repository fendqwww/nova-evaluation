import type { CalendarDay } from "@/shared/lib/calendar-day";

/**
 * Один юридический документ — в одном виде для всех трёх экранов, где он
 * появляется: страница на сайте, модалка в настройках и экран согласия при
 * первом запуске.
 *
 * Раньше текстов было два комплекта: «инженерный» в приложении и «юридический»
 * на лендинге, и они расходились — в приложении было написано, что фото не
 * уходят в Google, а на лендинге, что уходят. Для документа, который является
 * основанием обработки персональных данных, две редакции — это не дублирование,
 * а два разных обещания, из которых одно заведомо ложное. Отсюда один источник.
 */

export type LegalDocumentId = "privacy" | "offer" | "consent" | "recommendations";

export interface LegalSection {
  heading: string;
  paragraphs?: readonly string[];
  bullets?: readonly string[];
}

export interface LegalDocument {
  id: LegalDocumentId;
  /** Полное название, как оно печатается в заголовке. */
  title: string;
  /** Короткое имя для строки в списке настроек. */
  shortTitle: string;
  /** Одно предложение о том, что это за документ. */
  summary: string;
  /**
   * Версия — день последнего изменения текста.
   *
   * Это не украшение и не «обновлено такого-то»: версия записывается в
   * UserConsent вместе с датой акцепта, и именно она позволяет ответить на
   * вопрос «с какой редакцией согласился этот человек». Изменение версии
   * обязательных документов заставляет всех пользователей принять их заново
   * (см. features/legal/server/consent.repository.ts).
   */
  version: CalendarDay;
  /** Путь публичной страницы — на неё ведут ссылки из бота и из писем. */
  path: string;
  sections: readonly LegalSection[];
}
