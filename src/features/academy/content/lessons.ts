/**
 * Академия Nova — уроки в коде.
 *
 * ПОЧЕМУ В КОДЕ, А НЕ В БАЗЕ: то же, что и в библиотеке. Урок — редакторский
 * материал, одинаковый для всех и меняющийся вместе с релизом. В базе живёт
 * только факт прохождения (модель AcademyProgress), потому что он принадлежит
 * человеку, а текст — нет.
 *
 * ЧТО ЗДЕСЬ СЧИТАЕТСЯ УРОКОМ. Пять минут чтения и одно действие в конце. Не
 * статья и не глава: урок, после которого нечего сделать, — это контент, а не
 * обучение, поэтому у каждого есть `takeaway` — конкретное действие — и, где
 * возможно, `target` — раздел, в котором это действие выполняется.
 *
 * ЧТО ЗДЕСЬ ЗАПРЕЩЕНО. Медицинские утверждения, диагнозы, назначения препаратов и
 * добавок, обещания результата к дате. Все числа — общепринятые ориентиры из тех
 * же источников, на которых стоят формулы приложения (см. lib/targets.ts и
 * features/sleep/lib/score.ts), а не выдуманные под красивый текст.
 */

