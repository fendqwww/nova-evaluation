/**
 * Правила, по которым бот решает написать.
 *
 * Все числа собраны здесь, потому что это единственная часть системы, которую
 * будут крутить по результатам: тексты правятся, пороги двигаются, а логика
 * планировщика остаётся прежней.
 */

/** Что бот умеет отправлять. Значения попадают в BotDelivery.kind. */
export const NOTIFICATION_KINDS = ["morning", "evening", "winback"] as const;
export type NotificationKind = (typeof NOTIFICATION_KINDS)[number];

/**
 * Не больше двух сообщений в сутки: утреннее и вечернее.
 *
 * Возвратное (winback) идёт вместо утреннего, а не в дополнение — человеку,
 * который не заходил неделю, бессмысленно писать «вчера вы спали 6 часов»:
 * данных за вчера у него нет.
 */
export const MAX_MESSAGES_PER_DAY = 2;

/* ------------------------------------------------------------- окна --- */

/**
 * Часы в локальном времени пользователя, когда допустима отправка.
 *
 * Утро — 8:00–11:00. Не в 6:00: сообщение, разбудившее человека, отключают
 * вместе с приложением. Вечер — 19:00–22:00, до того как люди ложатся.
 *
 * Планировщик просыпается раз в час, поэтому окно шире одного часа: иначе
 * пользователь в часовом поясе, чей «девять утра» пришёлся между запусками,
 * не получил бы ничего.
 */
export const MORNING_WINDOW = { from: 8, to: 11 } as const;
export const EVENING_WINDOW = { from: 19, to: 22 } as const;

/* -------------------------------------------------------- возвраты --- */

/**
 * Со скольких дней отсутствия человек считается ушедшим.
 *
 * Два дня — это выходные, а не потеря пользователя. Три — уже перерыв, о
 * котором уместно напомнить.
 */
export const WINBACK_AFTER_DAYS = 3;

/**
 * Как часто напоминать ушедшему.
 *
 * Раз в неделю, бессрочно — так решил владелец продукта. Риск известен и
 * принят: Telegram банит ботов по жалобам, а человек, ушедший полгода назад,
 * нажимает «Спам» охотнее, чем возвращается. Поэтому в каждом возвратном
 * сообщении есть кнопка «Больше не писать», а блокировка бота отписывает
 * автоматически — см. BotSubscriber.
 */
export const WINBACK_EVERY_DAYS = 7;

/* -------------------------------------------------------- команды --- */

/**
 * Меню команд, которое Telegram показывает рядом с полем ввода.
 *
 * Пять штук и ни одной лишней. Команда, о которой нужно догадаться, не
 * существует; команда, которую видно, но которая дублирует кнопку, — шум.
 * Здесь каждая отвечает на вопрос, который нельзя закрыть, открыв приложение:
 * «что у меня сегодня» — быстрый ответ без запуска, «не пиши мне» — то, чего в
 * приложении нет вовсе.
 */
export const BOT_COMMANDS: ReadonlyArray<{ command: string; description: string }> = [
  { command: "start", description: "Открыть Nova" },
  { command: "today", description: "Что у меня сегодня" },
  { command: "streak", description: "Мои серии и прогресс" },
  { command: "help", description: "Что умеет Nova" },
  { command: "stop", description: "Не присылать напоминания" },
];
