import "server-only";
import { resolveIdentity } from "@/server/auth/identity";
import { isSupportAdmin } from "@/features/support/server/admins";

/**
 * Кто имеет право видеть панель.
 *
 * ПОЧЕМУ ТЕПЕРЬ ПО TELEGRAM-ID, А НЕ ПО ПАРОЛЮ. Панель жила отдельной страницей
 * в браузере, и там пароль был единственным возможным замком: снаружи Telegram
 * нет initData, то есть нет подписи, которой можно верить, и присланный из
 * браузера «я такой-то» — просто строка. Внутри Mini App всё наоборот: личность
 * приходит подписанной Telegram и проверяется на каждом действии
 * (resolveIdentity), поэтому сравнение с известным id — более сильная проверка,
 * чем общий секрет, который можно переслать в сообщении.
 *
 * ПОЧЕМУ СПИСОК ТОТ ЖЕ, ЧТО У ПОДДЕРЖКИ. SUPPORT_ADMIN_IDS уже заполнен, уже
 * содержит числовые id (не имена пользователей — их можно сменить и занять
 * чужое), и это те же самые люди: тот, кто разбирает тикеты, и есть тот, кто
 * смотрит, как идут дела у продукта. Вторая переменная с тем же содержимым
 * означала бы два списка, которые однажды разойдутся, и доступ, забытый в одном
 * из них.
 *
 * РАЗРАБОТКА. Локально resolveIdentity выдаёт подставного пользователя, чьего
 * id нет ни в одном списке, — без этой ветки панель нельзя было бы открыть на
 * своей машине вовсе. Ветка сужена до NODE_ENV === "development": на Vercel
 * сборка идёт с "production", поэтому в проде её не существует.
 */
export function isAppAdmin(telegramId: string): boolean {
  if (process.env.NODE_ENV === "development") return true;
  return isSupportAdmin(telegramId);
}

/**
 * Проверка на входе в серверное действие.
 *
 * Бросает, а не возвращает false: у вызывающего нет осмысленного продолжения
 * без прав, и молчаливый пустой ответ скрыл бы отказ там, где его надо видеть.
 * Экран ловит это сообщение и показывает «раздел недоступен».
 */
export function requireAdmin(rawInitData: string | undefined): void {
  const identity = resolveIdentity(rawInitData);
  if (!isAppAdmin(identity.telegramId)) throw new Error("ADMIN_FORBIDDEN");
}
