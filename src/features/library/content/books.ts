/** Проблемы, на которые книга отвечает. Совпадают с id из lib/problems.ts. */
export type LibraryProblemId =
  | "quits_early"
  | "no_system"
  | "sleep_debt"
  | "sleep_chaos"
  | "diet_unknown"
  | "overeating"
  | "no_training"
  | "no_progression"
  | "no_focus"
  | "money";

export interface LibraryBook {
  id: string;
  title: string;
  author: string;
  /** Год оригинального издания. */
  year: number;
  category: LibraryCategory;
  /** О чём книга — одна строка, без рекламы. */
  summary: string;
  /** Три мысли, которые останутся после прочтения. */
  keyIdeas: string[];
  /** Проблемы, которые эта книга действительно решает. */
  solves: LibraryProblemId[];
  /** Примерное время чтения в часах — чтобы выбор был осознанным. */
  hours: number;
}

