/**
 * Библиотека Nova — каталог в коде, а не в базе.
 *
 * ПОЧЕМУ В КОДЕ. Это редакторский материал: он меняется вместе с релизом и
 * одинаков для всех пользователей. Таблица означала бы миграцию на каждую
 * правку опечатки и админку, которой в проекте нет. В базе лежит только то, что
 * принадлежит человеку, — а здесь не принадлежит ничего.
 *
 * ПОЧЕМУ КАЖДАЯ КНИГА НЕСЁТ `solves`. Полка с пятнадцатью хорошими книгами
 * бесполезна человеку, который не знает, что делать: это ещё один список, из
 * которого надо выбирать. Ценность появляется, когда книга названа ответом на
 * конкретную проблему этого человека — «ты бросаешь цели через неделю» →
 * «Атомные привычки». `solves` — это связь с диагнозом (см. lib/problems.ts), и
 * именно она превращает каталог в рекомендацию.
 *
 * Ни одной выдуманной книги. Все существуют в русском переводе; год — год
 * оригинала. Ссылок на магазины здесь нет намеренно: приложение о здоровье не
 * должно выглядеть как витрина.
 */

