/**
 * Сценарий питания — что делать не сегодня, а следующие четыре недели.
 *
 * ЗАЧЕМ ОТДЕЛЬНАЯ СУЩНОСТЬ. Норма отвечает на «сколько», меню — на «что именно
 * сегодня». Оба ответа про один день, и человек, честно закрывший свой первый
 * день, наутро получает ровно ту же задачу заново. Отсюда обычная судьба таких
 * приложений: две недели дисциплины, потом тишина. Не хватает третьего ответа —
 * «а к чему это идёт и что изменится через неделю».
 *
 * ПОЧЕМУ ЭТО КОНСТАНТЫ, А НЕ ЗАПРОС К МОДЕЛИ. Сценарий не зависит от сегодняшних
 * данных: последовательность «сначала создать дефицит, потом добрать белок, потом
 * добавить активность» одинакова для всех, кто худеет, и придумывать её заново на
 * каждого пользователя значит платить токенами за один и тот же ответ и рисковать
 * тем, что модель на третьей неделе посоветует что-нибудь своё. Персонализация в
 * этом разделе живёт там, где ей место: в цифрах нормы, которые посчитаны по телу
 * человека, и в разборе коуча, который смотрит на его записи.
 *
 * ЧЕГО ЗДЕСЬ НЕТ И НЕ ДОЛЖНО БЫТЬ. Медицинских утверждений, обещаний срока
 * («минус 8 кг за месяц») и запретов продуктов. Первое — не наша компетенция,
 * второе — враньё при любой честной формулировке, третье не работает.
 */

import type { NutritionAim } from "@/features/nutrition/lib/targets";

export interface NutritionScenarioWeek {
  /** Номер недели, с первой. */
  week: number;
  title: string;
  /** Одна мысль недели — то, что человек должен запомнить, если забудет всё. */
  focus: string;
  /** Два–четыре конкретных действия. Не принципы: действия. */
  actions: string[];
}

export interface NutritionScenario {
  aim: NutritionAim;
  title: string;
  /** Чем этот сценарий отличается от двух других, одной строкой. */
  summary: string;
  /** Что человек почувствует, если сценарий сработал. Не цифра, а признак. */
  signal: string;
  weeks: NutritionScenarioWeek[];
}

